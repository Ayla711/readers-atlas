// node tools/build_index.js <app dir> [--check]: writes data/index.js, the table that tells the app which countries
// to load for a linked place, book, author or region (js/app.js loadUntilFound), so that a shared link does not have
// to load every country in turn. Called by build_countries.py; --check only compares (tools/validate.js).
//   window.RA_INDEX = { place: { "<codes>": "<ids>" }, book: {…}, author: {…}, region: {…} }
// and prints, for build_countries.py, which other countries each country needs loaded first ("needs").
// <codes>: the countries to load, space-separated, the one holding the record first; <ids>: space-separated.
const fs = require("fs"), vm = require("vm"), path = require("path");
const app = process.argv[2], check = process.argv.includes("--check");
const slug = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); // as in js/app.js
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(app, "data/countries.js"), "utf8"), ctx);
const open = ctx.window.RA_COUNTRIES.filter((c) => c.open);
const add = (map, id, code, first) => { if (!map.has(id)) map.set(id, []); const a = map.get(id); if (!a.includes(code)) first ? a.unshift(code) : a.push(code); };
const place = new Map(), region = new Map(), bookHome = new Map(), bookUse = new Map(), bookAuthor = new Map();
const own = new Map(); // country -> ids of the books its own files hold
for (const c of open) {
  const w = { window: { RA_DATA: {}, RA_GEO: null } }; vm.createContext(w);
  for (const f of c.data || []) vm.runInContext(fs.readFileSync(path.join(app, f), "utf8"), w);
  const d = w.window.RA_DATA, geo = w.window.RA_GEO;
  for (const r of (geo && geo.regions) || []) add(region, r.id, c.code);
  for (const p of d.places || []) { add(place, p.id, c.code); for (const b of p.book_ids || []) add(bookUse, b, c.code); }
  for (const l of d.lines || []) if (l.status !== "rejected") add(bookUse, l.book_id, c.code);
  for (const b of d.books || []) { if (!bookHome.has(b.id)) bookHome.set(b.id, c.code); bookAuthor.set(b.id, slug(b.author)); }
  own.set(c.code, new Set((d.books || []).map((b) => b.id)));
}
// a book: the first country whose files hold its record, then every country with a place or a line of it
const book = new Map(), author = new Map();
for (const [id, home] of bookHome) {
  const use = bookUse.get(id) || [];
  const codes = use.includes(home) ? [home, ...use.filter((x) => x !== home)] : [home, ...use];
  book.set(id, codes);
  for (const code of codes) add(author, bookAuthor.get(id), code);
}
// a country "needs" another when one of its places or lines belongs to a book whose record is only in the other's
// files (Yalta's Chekhov is a Russian book): the app loads those first (data/countries.js, "needs")
const needs = {};
for (const c of open) needs[c.code] = [];
for (const [id, codes] of bookUse) for (const code of codes) {
  if (own.get(code).has(id) || !bookHome.has(id)) continue;
  needs[code].includes(bookHome.get(id)) || needs[code].push(bookHome.get(id));
}
for (const k of Object.keys(needs)) if (!needs[k].length) delete needs[k];
const pack = (map) => { const out = {}; for (const [id, codes] of map) { const k = codes.join(" "); out[k] = out[k] ? out[k] + " " + id : id; } return out; };
for (const m of [place, book, author, region]) for (const id of m.keys()) if (/\s/.test(id)) throw new Error("id with a space: " + id);
const text = "// Generated by tools/build_index.js (run by tools/build_countries.py). Do not edit by hand.\n"
  + "window.RA_INDEX = " + JSON.stringify({ place: pack(place), book: pack(book), author: pack(author), region: pack(region) }) + ";\n";
const out = path.join(app, "data/index.js");
if (check) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== text) { console.log("data/index.js is out of date: run python3 -I tools/build_countries.py"); process.exit(1); }
  const have = {}; for (const c of open) if (c.needs) have[c.code] = c.needs;
  if (JSON.stringify(have) !== JSON.stringify(needs)) { console.log('data/countries.js "needs" is out of date: run python3 -I tools/build_countries.py'); process.exit(1); }
} else {
  fs.writeFileSync(out, text);
  console.log(JSON.stringify({ places: place.size, books: book.size, authors: author.size, regions: region.size, bytes: Buffer.byteLength(text), needs }));
}
